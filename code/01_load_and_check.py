# -*- coding: utf-8 -*-
"""
第 2 步：读入数据 + 数据检查（QC）
=========================================================
数据集：某光伏电站 2019 全年 15 分钟粒度观测（单站）
文件   ：data/ningxia_2019_15min.xlsx
目标列 ：实际功率（电站实际交流输出功率，kW）

怎么运行：PyCharm 里右键本文件 -> 运行 '01_load_and_check'
=========================================================
"""
import pandas as pd

# ---------------------------------------------------------
# 0) 路径与列名（你以后换数据，只要改这两行）
# ---------------------------------------------------------
DATA_PATH = "/Users/xuminchun/Desktop/电气club作业/data/ningxia_2019_15min.xlsx"
TIME_COL = "采样结束时刻"     # 用「结束时刻」作为这一条数据的时间点
RAD_COL = "GTI（固定倾角辐射）"  # 固定倾角板上接收到的辐射：最强特征
TARGET = "实际功率"           # 我们要预测的目标

# ---------------------------------------------------------
# 1) 读入数据
#    read_excel 需要 openpyxl（你的 conda 里已装 3.1.5），可直接跑
# ---------------------------------------------------------
df = pd.read_excel(DATA_PATH)

# ---------------------------------------------------------
# 2) 把时间列转成真正的「日期时间」类型
#    为什么要转？只有转成 datetime，才能按小时/按月统计、画时间序列。
#    不转的话它只是一串文字，机器看不出先后。
# ---------------------------------------------------------
df[TIME_COL] = pd.to_datetime(df[TIME_COL])

# ---------------------------------------------------------
# 3) 基本体检
# ---------------------------------------------------------
print("=" * 56)
print("1) 基本规模：行数 =", len(df), "  列数 =", df.shape[1])

print("2) 时间范围：", df[TIME_COL].min(), " ~ ", df[TIME_COL].max())

# 只打印有缺失的列（没有缺失的话就打印"无缺失"）
missing = df.isna().sum()
print("3) 缺失值检查：")
if missing.sum() == 0:
    print("   全部 20 列零缺失")
else:
    print(missing[missing > 0].to_string())

print("4) 重复时间戳条数：", df[TIME_COL].duplicated().sum())

# ---------------------------------------------------------
# 4) 目标列体检
# ---------------------------------------------------------
print("=" * 56)
print("5) 目标列『实际功率』统计：")
print(df[TARGET].describe().to_string())
print("   负值个数：", (df[TARGET] < 0).sum())
print("   零值占比：%.1f%%" % (100 * (df[TARGET] == 0).mean()))

# ---------------------------------------------------------
# 5) 物理一致性检查（找异常）
#    判据用「总辐射 GHI（太阳总水平辐射）」，不要用 GTI：
#    GHI 是太阳到底出来没有的判断标准；GTI 是斜面上测的辐射，
#    数值可能比 GHI 大 1~2（因为斜面更朝向太阳），拿它当"有没有太阳"
#    会误判。下面三条才是真的违反物理：
#      a) 太阳完全没出来(GHI=0) 却发电  -> 矛盾
#      b) 有太阳(GHI>0) 却功率为负      -> 矛盾
#      c) 功率超过装机容量(130 kW)      -> 矛盾
#    另：GTI=0 但功率=0.125 这类，一般出现在日出/日落瞬间
#    （GHI=1 W/m²，斜面上四舍五入成了 0），属于正常边界，不算异常。
# ---------------------------------------------------------
GHI_COL = "GHI（太阳总水平辐射）"
CAPACITY_KW = 130.0          # 电站装机容量上界，用于兜底检查

bad_a = df[(df[GHI_COL] == 0) & (df[TARGET] > 0)]
bad_b = df[(df[GHI_COL] > 0) & (df[TARGET] < 0)]
bad_c = df[df[TARGET] > CAPACITY_KW]

print("=" * 56)
print("6) 物理一致性检查（严格判据）")
print("   太阳没出来(GHI=0)却发电 :", len(bad_a), "条")
print("   有太阳(GHI>0)却负功率   :", len(bad_b), "条")
print("   功率超过 %.0f kW        : %d 条" % (CAPACITY_KW, len(bad_c)))
print("   >>> 结论：真正违反物理的异常 =",
      len(bad_a) + len(bad_b) + len(bad_c), "条")

# 边界情况：GHI=1 W/m²（日出/日落）这一档，看看功率长什么样
edge = df[df[GHI_COL] == 1]
if len(edge):
    print("\n   边界检查：GHI=1 W/m² 的行有 %d 条，"
          "其中功率>0 的占 %.0f%%，功率区间 %.5f ~ %.5f kW"
          % (len(edge), 100 * (edge[TARGET] > 0).mean(),
             edge[TARGET].min(), edge[TARGET].max()))
    print("   （这一档全部是日出/日落，属正常物理响应，不是脏数据）")

# ---------------------------------------------------------
# 6) 目标 vs 辐射 的确定性关系（重要发现，需向数据提供方核实）
#    用最小二乘看功率是不是辐射的"固定倍数"
# ---------------------------------------------------------
import numpy as np
G = df[GHI_COL].values.astype(float)
P = df[TARGET].values.astype(float)
k, b = np.polyfit(G, P, 1)          # 直线拟合：P = k*G + b
res = P - (k * G + b)               # 残差 = 实际 - 拟合
print("=" * 56)
print("7) 功率 与 总辐射 的线性关系")
print("   P ≈ %.6f × GHI + %.5f" % (k, b))
print("   残差最大 |e| = %.4f kW       （满发约 128 kW，占 %.2f%%）"
      % (np.abs(res).max(), 100 * np.abs(res).max() / P.max()))
for c in ["气温", "云层不透明度", "高度10m风速"]:
    cc = np.corrcoef(res, df[c].values)[0, 1]
    print("   残差 与 %-10s 相关系数 = %+.4f" % (c, cc))

# ---------------------------------------------------------
# 8) 按月覆盖率（检查有没有哪个月缺数据）
# ---------------------------------------------------------
df["月"] = df[TIME_COL].dt.month
print("=" * 56)
print("7) 每月条数：")
print(df["月"].value_counts().sort_index().to_string())

print("=" * 56)
print("[OK] 数据检查跑完，把上面这段输出发我即可。")
